fn put_u32_triplet(output: &mut [u8], value: [u32; 3]) {
    for (index, item) in value.into_iter().enumerate() {
        let offset = index * 4;
        output[offset..offset + 4].copy_from_slice(&item.to_le_bytes());
    }
}

fn read_u32_triplet(bytes: &[u8]) -> [u32; 3] {
    [
        read_u32(&bytes[..4]),
        read_u32(&bytes[4..8]),
        read_u32(&bytes[8..12]),
    ]
}

fn read_u16(bytes: &[u8]) -> u16 {
    u16::from_le_bytes(bytes.try_into().expect("fixed u16 slice"))
}

fn read_u32(bytes: &[u8]) -> u32 {
    u32::from_le_bytes(bytes.try_into().expect("fixed u32 slice"))
}

fn read_u64(bytes: &[u8]) -> u64 {
    u64::from_le_bytes(bytes.try_into().expect("fixed u64 slice"))
}

fn checksum(bytes: &[u8]) -> [u8; 32] {
    let mut digest = Sha256::new();
    digest.update(CHECKSUM_DOMAIN_V1);
    digest.update(bytes);
    digest.finalize().into()
}

fn write_hex(formatter: &mut fmt::Formatter<'_>, bytes: &[u8]) -> fmt::Result {
    for byte in bytes {
        write!(formatter, "{byte:02x}")?;
    }
    Ok(())
}

