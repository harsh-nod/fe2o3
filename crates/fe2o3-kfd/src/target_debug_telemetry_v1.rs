/// Versioned cooperative target payload.
#[derive(Clone, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub enum KfdTargetDebugTelemetryPayloadV1 {
    SessionStarted {
        process_instance: KfdTargetDebugTelemetryDigestV1,
        executable: KfdTargetDebugArtifactIdentityV1,
    },
    Artifact {
        role: KfdTargetDebugArtifactRoleV1,
        ordinal: u32,
        artifact: KfdTargetDebugArtifactIdentityV1,
    },
    Dispatch {
        phase: KfdTargetDebugDispatchPhaseV1,
        dispatch: KfdTargetDebugTelemetryDigestV1,
        kernel: KfdTargetDebugTelemetryDigestV1,
        code_object: KfdTargetDebugTelemetryDigestV1,
        logical_queue: KfdTargetDebugTelemetryDigestV1,
        grid: [u32; 3],
        workgroup: [u32; 3],
        dynamic_shared_memory_bytes: u32,
    },
    Allocation {
        phase: KfdTargetDebugAllocationPhaseV1,
        memory_kind: KfdTargetDebugMemoryKindV1,
        access: KfdTargetDebugMemoryAccessV1,
        allocation: KfdTargetDebugTelemetryDigestV1,
        logical_scope: KfdTargetDebugTelemetryDigestV1,
        byte_length: u64,
        alignment: u64,
    },
    Diagnostic {
        severity: KfdTargetDebugDiagnosticSeverityV1,
        stable_code: u32,
        diagnostic: KfdTargetDebugTelemetryDigestV1,
        logical_scope: KfdTargetDebugTelemetryDigestV1,
    },
    SessionEnded {
        outcome: KfdTargetDebugSessionOutcomeV1,
    },
}

impl KfdTargetDebugTelemetryPayloadV1 {
    /// Validates cross-field constraints that are not represented by the field types.
    pub fn validate(&self) -> Result<(), KfdTargetDebugTelemetryDataErrorV1> {
        match self {
            Self::Dispatch {
                grid, workgroup, ..
            } => {
                for axis in 0..3 {
                    if grid[axis] == 0 || workgroup[axis] == 0 {
                        return Err(KfdTargetDebugTelemetryDataErrorV1::ZeroDimension { axis });
                    }
                    if workgroup[axis] > grid[axis] {
                        return Err(KfdTargetDebugTelemetryDataErrorV1::WorkgroupExceedsGrid {
                            axis,
                            grid: grid[axis],
                            workgroup: workgroup[axis],
                        });
                    }
                }
            }
            Self::Allocation {
                byte_length,
                alignment,
                ..
            } => {
                if *byte_length == 0 {
                    return Err(KfdTargetDebugTelemetryDataErrorV1::ZeroLength);
                }
                if *alignment == 0 || !alignment.is_power_of_two() {
                    return Err(KfdTargetDebugTelemetryDataErrorV1::InvalidAlignment(
                        *alignment,
                    ));
                }
            }
            Self::Diagnostic { stable_code, .. } if *stable_code == 0 => {
                return Err(KfdTargetDebugTelemetryDataErrorV1::ZeroDiagnosticCode);
            }
            _ => {}
        }
        Ok(())
    }

    fn wire_kind(&self) -> u16 {
        match self {
            Self::SessionStarted { .. } => 1,
            Self::Artifact { .. } => 2,
            Self::Dispatch { .. } => 3,
            Self::Allocation { .. } => 4,
            Self::Diagnostic { .. } => 5,
            Self::SessionEnded { .. } => 6,
        }
    }

    fn encode_payload(&self, output: &mut [u8; PAYLOAD_CAPACITY_V1]) -> usize {
        match self {
            Self::SessionStarted {
                process_instance,
                executable,
            } => {
                output[..32].copy_from_slice(process_instance.as_bytes());
                output[32..64].copy_from_slice(executable.digest().as_bytes());
                output[64..72].copy_from_slice(&executable.byte_length().to_le_bytes());
                72
            }
            Self::Artifact {
                role,
                ordinal,
                artifact,
            } => {
                output[..2].copy_from_slice(&(*role as u16).to_le_bytes());
                output[4..8].copy_from_slice(&ordinal.to_le_bytes());
                output[8..40].copy_from_slice(artifact.digest().as_bytes());
                output[40..48].copy_from_slice(&artifact.byte_length().to_le_bytes());
                48
            }
            Self::Dispatch {
                phase,
                dispatch,
                kernel,
                code_object,
                logical_queue,
                grid,
                workgroup,
                dynamic_shared_memory_bytes,
            } => {
                output[..2].copy_from_slice(&(*phase as u16).to_le_bytes());
                put_u32_triplet(&mut output[4..16], *grid);
                put_u32_triplet(&mut output[16..28], *workgroup);
                output[28..32].copy_from_slice(&dynamic_shared_memory_bytes.to_le_bytes());
                output[32..64].copy_from_slice(dispatch.as_bytes());
                output[64..96].copy_from_slice(kernel.as_bytes());
                output[96..128].copy_from_slice(code_object.as_bytes());
                output[128..160].copy_from_slice(logical_queue.as_bytes());
                160
            }
            Self::Allocation {
                phase,
                memory_kind,
                access,
                allocation,
                logical_scope,
                byte_length,
                alignment,
            } => {
                output[..2].copy_from_slice(&(*phase as u16).to_le_bytes());
                output[2..4].copy_from_slice(&(*memory_kind as u16).to_le_bytes());
                output[4..6].copy_from_slice(&(*access as u16).to_le_bytes());
                output[8..16].copy_from_slice(&byte_length.to_le_bytes());
                output[16..24].copy_from_slice(&alignment.to_le_bytes());
                output[24..56].copy_from_slice(allocation.as_bytes());
                output[56..88].copy_from_slice(logical_scope.as_bytes());
                88
            }
            Self::Diagnostic {
                severity,
                stable_code,
                diagnostic,
                logical_scope,
            } => {
                output[..2].copy_from_slice(&(*severity as u16).to_le_bytes());
                output[4..8].copy_from_slice(&stable_code.to_le_bytes());
                output[8..40].copy_from_slice(diagnostic.as_bytes());
                output[40..72].copy_from_slice(logical_scope.as_bytes());
                72
            }
            Self::SessionEnded { outcome } => {
                output[..2].copy_from_slice(&(*outcome as u16).to_le_bytes());
                2
            }
        }
    }

    fn decode_payload(
        kind: u16,
        bytes: &[u8],
    ) -> Result<Self, KfdTargetDebugTelemetryProtocolErrorV1> {
        let payload = match kind {
            1 => {
                require_payload_len(bytes, 72)?;
                Self::SessionStarted {
                    process_instance: decode_digest(&bytes[..32])?,
                    executable: decode_artifact(&bytes[32..64], &bytes[64..72])?,
                }
            }
            2 => {
                require_payload_len(bytes, 48)?;
                require_zero("artifact reserved", &bytes[2..4])?;
                Self::Artifact {
                    role: KfdTargetDebugArtifactRoleV1::from_wire(read_u16(&bytes[..2]))?,
                    ordinal: read_u32(&bytes[4..8]),
                    artifact: decode_artifact(&bytes[8..40], &bytes[40..48])?,
                }
            }
            3 => {
                require_payload_len(bytes, 160)?;
                require_zero("dispatch reserved", &bytes[2..4])?;
                Self::Dispatch {
                    phase: KfdTargetDebugDispatchPhaseV1::from_wire(read_u16(&bytes[..2]))?,
                    grid: read_u32_triplet(&bytes[4..16]),
                    workgroup: read_u32_triplet(&bytes[16..28]),
                    dynamic_shared_memory_bytes: read_u32(&bytes[28..32]),
                    dispatch: decode_digest(&bytes[32..64])?,
                    kernel: decode_digest(&bytes[64..96])?,
                    code_object: decode_digest(&bytes[96..128])?,
                    logical_queue: decode_digest(&bytes[128..160])?,
                }
            }
            4 => {
                require_payload_len(bytes, 88)?;
                require_zero("allocation reserved", &bytes[6..8])?;
                Self::Allocation {
                    phase: KfdTargetDebugAllocationPhaseV1::from_wire(read_u16(&bytes[..2]))?,
                    memory_kind: KfdTargetDebugMemoryKindV1::from_wire(read_u16(&bytes[2..4]))?,
                    access: KfdTargetDebugMemoryAccessV1::from_wire(read_u16(&bytes[4..6]))?,
                    byte_length: read_u64(&bytes[8..16]),
                    alignment: read_u64(&bytes[16..24]),
                    allocation: decode_digest(&bytes[24..56])?,
                    logical_scope: decode_digest(&bytes[56..88])?,
                }
            }
            5 => {
                require_payload_len(bytes, 72)?;
                require_zero("diagnostic reserved", &bytes[2..4])?;
                Self::Diagnostic {
                    severity: KfdTargetDebugDiagnosticSeverityV1::from_wire(read_u16(&bytes[..2]))?,
                    stable_code: read_u32(&bytes[4..8]),
                    diagnostic: decode_digest(&bytes[8..40])?,
                    logical_scope: decode_digest(&bytes[40..72])?,
                }
            }
            6 => {
                require_payload_len(bytes, 2)?;
                Self::SessionEnded {
                    outcome: KfdTargetDebugSessionOutcomeV1::from_wire(read_u16(bytes))?,
                }
            }
            _ => return Err(KfdTargetDebugTelemetryProtocolErrorV1::UnknownKind(kind)),
        };
        payload
            .validate()
            .map_err(KfdTargetDebugTelemetryProtocolErrorV1::InvalidPayload)?;
        Ok(payload)
    }
}

/// One decoded canonical telemetry record.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct KfdTargetDebugTelemetryRecordV1 {
    sequence: u64,
    session_nonce: KfdTargetDebugSessionNonceV1,
    payload: KfdTargetDebugTelemetryPayloadV1,
}

impl KfdTargetDebugTelemetryRecordV1 {
    pub fn new(
        sequence: u64,
        session_nonce: KfdTargetDebugSessionNonceV1,
        payload: KfdTargetDebugTelemetryPayloadV1,
    ) -> Result<Self, KfdTargetDebugTelemetryDataErrorV1> {
        payload.validate()?;
        Ok(Self {
            sequence,
            session_nonce,
            payload,
        })
    }

    pub const fn sequence(&self) -> u64 {
        self.sequence
    }

    pub const fn session_nonce(&self) -> KfdTargetDebugSessionNonceV1 {
        self.session_nonce
    }

    pub const fn payload(&self) -> &KfdTargetDebugTelemetryPayloadV1 {
        &self.payload
    }

    /// Serializes one record into a fully initialized canonical wire packet.
    pub fn to_wire_bytes(&self) -> [u8; KFD_TARGET_DEBUG_TELEMETRY_WIRE_LEN_V1] {
        let mut bytes = [0_u8; KFD_TARGET_DEBUG_TELEMETRY_WIRE_LEN_V1];
        bytes[..8].copy_from_slice(&MAGIC_V1);
        bytes[8..10].copy_from_slice(&VERSION_V1.to_le_bytes());
        bytes[10..12].copy_from_slice(&self.payload.wire_kind().to_le_bytes());
        bytes[16..24].copy_from_slice(&self.sequence.to_le_bytes());
        bytes[24..56].copy_from_slice(self.session_nonce.as_bytes());
        let mut payload = [0_u8; PAYLOAD_CAPACITY_V1];
        let payload_len = self.payload.encode_payload(&mut payload);
        bytes[12..16].copy_from_slice(&(payload_len as u32).to_le_bytes());
        bytes[HEADER_LEN_V1..CHECKSUM_OFFSET_V1].copy_from_slice(&payload);
        let checksum = checksum(&bytes[..CHECKSUM_OFFSET_V1]);
        bytes[CHECKSUM_OFFSET_V1..].copy_from_slice(&checksum);
        bytes
    }

    /// Decodes one exact packet and rejects noncanonical reserved or padding bytes.
    pub fn from_wire_bytes(bytes: &[u8]) -> Result<Self, KfdTargetDebugTelemetryProtocolErrorV1> {
        if bytes.len() != KFD_TARGET_DEBUG_TELEMETRY_WIRE_LEN_V1 {
            return Err(KfdTargetDebugTelemetryProtocolErrorV1::InvalidWireLength {
                expected: KFD_TARGET_DEBUG_TELEMETRY_WIRE_LEN_V1,
                actual: bytes.len(),
            });
        }
        if bytes[..8] != MAGIC_V1 {
            return Err(KfdTargetDebugTelemetryProtocolErrorV1::InvalidMagic);
        }
        let version = read_u16(&bytes[8..10]);
        if version != VERSION_V1 {
            return Err(KfdTargetDebugTelemetryProtocolErrorV1::UnsupportedVersion(
                version,
            ));
        }
        let payload_len = usize::try_from(read_u32(&bytes[12..16])).map_err(|_| {
            KfdTargetDebugTelemetryProtocolErrorV1::InvalidPayloadLength {
                capacity: PAYLOAD_CAPACITY_V1,
                actual: usize::MAX,
            }
        })?;
        if payload_len > PAYLOAD_CAPACITY_V1 {
            return Err(
                KfdTargetDebugTelemetryProtocolErrorV1::InvalidPayloadLength {
                    capacity: PAYLOAD_CAPACITY_V1,
                    actual: payload_len,
                },
            );
        }
        let expected = checksum(&bytes[..CHECKSUM_OFFSET_V1]);
        if bytes[CHECKSUM_OFFSET_V1..] != expected {
            return Err(KfdTargetDebugTelemetryProtocolErrorV1::ChecksumMismatch);
        }
        require_zero(
            "payload padding",
            &bytes[HEADER_LEN_V1 + payload_len..CHECKSUM_OFFSET_V1],
        )?;
        let session_nonce = KfdTargetDebugSessionNonceV1::from_bytes(
            bytes[24..56].try_into().expect("fixed nonce slice"),
        )
        .map_err(KfdTargetDebugTelemetryProtocolErrorV1::InvalidPayload)?;
        let payload = KfdTargetDebugTelemetryPayloadV1::decode_payload(
            read_u16(&bytes[10..12]),
            &bytes[HEADER_LEN_V1..HEADER_LEN_V1 + payload_len],
        )?;
        Ok(Self {
            sequence: read_u64(&bytes[16..24]),
            session_nonce,
            payload,
        })
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum TelemetryLifecycleV1 {
    AwaitingStart,
    Active,
    Finished,
}

/// Debugger-side receiver for one cooperative target session.
///
/// Every packet must carry kernel-supplied Linux credentials for the captured
/// target process. A successfully consumed protocol violation poisons this
/// endpoint because sequence and lifecycle recovery would be ambiguous.
pub struct KfdDebuggerTelemetryEndpointV1 {
    endpoint: OwnedFd,
    nonce: KfdTargetDebugSessionNonceV1,
    target: KfdTargetDebugTelemetryProcessV1,
    next_sequence: u64,
    lifecycle: TelemetryLifecycleV1,
    poisoned: bool,
}

impl fmt::Debug for KfdDebuggerTelemetryEndpointV1 {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("KfdDebuggerTelemetryEndpointV1")
            .field("target", &self.target)
            .field("next_sequence", &self.next_sequence)
            .field("lifecycle", &self.lifecycle)
            .field("poisoned", &self.poisoned)
            .field("authority", &"telemetry-only")
            .finish_non_exhaustive()
    }
}

impl KfdDebuggerTelemetryEndpointV1 {
    pub fn admit(
        endpoint: OwnedFd,
        nonce: KfdTargetDebugSessionNonceV1,
        target: KfdTargetDebugTelemetryProcessV1,
    ) -> Result<Self, KfdTargetDebugTelemetryTransportErrorV1> {
        target.validate_current()?;
        validate_connected_seqpacket(&endpoint)?;
        set_socket_passcred(&endpoint, true)
            .map_err(KfdTargetDebugTelemetryTransportErrorV1::ConfigureCredentials)?;
        if !socket_passcred(&endpoint)
            .map_err(KfdTargetDebugTelemetryTransportErrorV1::InspectSocket)?
        {
            return Err(KfdTargetDebugTelemetryTransportErrorV1::CredentialsDisabled);
        }
        Ok(Self {
            endpoint,
            nonce,
            target,
            next_sequence: 0,
            lifecycle: TelemetryLifecycleV1::AwaitingStart,
            poisoned: false,
        })
    }

    /// Receives the next record, blocking until a packet or EOF is available.
    pub fn receive(
        &mut self,
    ) -> Result<KfdTargetDebugTelemetryRecordV1, KfdTargetDebugTelemetryTransportErrorV1> {
        self.receive_inner(RecvFlags::CMSG_CLOEXEC)?
            .ok_or(KfdTargetDebugTelemetryTransportErrorV1::EndpointNotReady)
    }

    /// Receives one immediately available record without blocking.
    pub fn try_receive(
        &mut self,
    ) -> Result<Option<KfdTargetDebugTelemetryRecordV1>, KfdTargetDebugTelemetryTransportErrorV1>
    {
        self.receive_inner(RecvFlags::CMSG_CLOEXEC | RecvFlags::DONTWAIT)
    }

    pub const fn is_finished(&self) -> bool {
        matches!(self.lifecycle, TelemetryLifecycleV1::Finished)
    }

    fn receive_inner(
        &mut self,
        flags: RecvFlags,
    ) -> Result<Option<KfdTargetDebugTelemetryRecordV1>, KfdTargetDebugTelemetryTransportErrorV1>
    {
        if self.poisoned {
            return Err(KfdTargetDebugTelemetryTransportErrorV1::Poisoned);
        }
        if self.is_finished() {
            return Err(KfdTargetDebugTelemetryTransportErrorV1::SessionFinished);
        }
        let received = receive_packet(&self.endpoint, flags, self.target);
        let bytes = match received {
            Ok(Some(bytes)) => bytes,
            Ok(None) => return Ok(None),
            Err(error) => {
                self.poisoned = true;
                return Err(error);
            }
        };
        let record = match KfdTargetDebugTelemetryRecordV1::from_wire_bytes(&bytes) {
            Ok(record) => record,
            Err(error) => {
                self.poisoned = true;
                return Err(error.into());
            }
        };
        if record.session_nonce != self.nonce {
            self.poisoned = true;
            return Err(KfdTargetDebugTelemetryTransportErrorV1::NonceMismatch);
        }
        if record.sequence != self.next_sequence {
            self.poisoned = true;
            return Err(KfdTargetDebugTelemetryTransportErrorV1::SequenceMismatch {
                expected: self.next_sequence,
                actual: record.sequence,
            });
        }
        if let Err(error) = admit_lifecycle(self.lifecycle, &record.payload) {
            self.poisoned = true;
            return Err(error.into());
        }
        self.next_sequence = self.next_sequence.checked_add(1).ok_or_else(|| {
            self.poisoned = true;
            KfdTargetDebugTelemetryTransportErrorV1::SequenceExhausted
        })?;
        self.lifecycle = next_lifecycle(self.lifecycle, &record.payload);
        Ok(Some(record))
    }
}

/// Cooperative target-side sender for one debugger session.
///
/// The target endpoint validates the connected debugger credentials captured
/// at channel provisioning time. It sends declarations only and accepts no
/// commands, preventing this telemetry path from becoming an authority grant.
pub struct KfdCooperativeTargetTelemetryEndpointV1 {
    endpoint: OwnedFd,
    nonce: KfdTargetDebugSessionNonceV1,
    debugger: KfdTargetDebugTelemetryProcessV1,
    next_sequence: u64,
    lifecycle: TelemetryLifecycleV1,
    poisoned: bool,
}

impl fmt::Debug for KfdCooperativeTargetTelemetryEndpointV1 {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("KfdCooperativeTargetTelemetryEndpointV1")
            .field("debugger", &self.debugger)
            .field("next_sequence", &self.next_sequence)
            .field("lifecycle", &self.lifecycle)
            .field("poisoned", &self.poisoned)
            .field("authority", &"telemetry-only")
            .finish_non_exhaustive()
    }
}

impl KfdCooperativeTargetTelemetryEndpointV1 {
    pub fn admit(
        endpoint: OwnedFd,
        nonce: KfdTargetDebugSessionNonceV1,
        debugger: KfdTargetDebugTelemetryProcessV1,
    ) -> Result<Self, KfdTargetDebugTelemetryTransportErrorV1> {
        debugger.validate_current()?;
        validate_connected_seqpacket(&endpoint)?;
        let peer = socket_peercred(&endpoint)
            .map_err(KfdTargetDebugTelemetryTransportErrorV1::InspectSocket)?;
        if !debugger.matches_credentials(
            peer.pid.as_raw_pid(),
            peer.uid.as_raw(),
            peer.gid.as_raw(),
        ) {
            return Err(KfdTargetDebugTelemetryTransportErrorV1::PeerCredentialMismatch);
        }
        Ok(Self {
            endpoint,
            nonce,
            debugger,
            next_sequence: 0,
            lifecycle: TelemetryLifecycleV1::AwaitingStart,
            poisoned: false,
        })
    }

    /// Sends one declaration with the endpoint-owned nonce and sequence number.
    pub fn send(
        &mut self,
        payload: KfdTargetDebugTelemetryPayloadV1,
    ) -> Result<KfdTargetDebugTelemetryRecordV1, KfdTargetDebugTelemetryTransportErrorV1> {
        if self.poisoned {
            return Err(KfdTargetDebugTelemetryTransportErrorV1::Poisoned);
        }
        if self.lifecycle == TelemetryLifecycleV1::Finished {
            return Err(KfdTargetDebugTelemetryTransportErrorV1::SessionFinished);
        }
        payload.validate()?;
        admit_lifecycle(self.lifecycle, &payload)?;
        self.debugger.validate_current()?;
        let record = KfdTargetDebugTelemetryRecordV1::new(self.next_sequence, self.nonce, payload)?;
        let bytes = record.to_wire_bytes();
        loop {
            match send(&self.endpoint, &bytes, SendFlags::NOSIGNAL) {
                Ok(actual) if actual == bytes.len() => break,
                Ok(actual) => {
                    self.poisoned = true;
                    return Err(KfdTargetDebugTelemetryTransportErrorV1::PartialSend {
                        expected: bytes.len(),
                        actual,
                    });
                }
                Err(rustix::io::Errno::INTR) => continue,
                Err(error) => {
                    self.poisoned = true;
                    return Err(KfdTargetDebugTelemetryTransportErrorV1::Send(error));
                }
            }
        }
        self.next_sequence = self.next_sequence.checked_add(1).ok_or_else(|| {
            self.poisoned = true;
            KfdTargetDebugTelemetryTransportErrorV1::SequenceExhausted
        })?;
        self.lifecycle = next_lifecycle(self.lifecycle, &record.payload);
        Ok(record)
    }

    pub const fn is_finished(&self) -> bool {
        matches!(self.lifecycle, TelemetryLifecycleV1::Finished)
    }
}

pub(super) fn validate_connected_seqpacket(
    endpoint: &OwnedFd,
) -> Result<(), KfdTargetDebugTelemetryTransportErrorV1> {
    let domain =
        socket_domain(endpoint).map_err(KfdTargetDebugTelemetryTransportErrorV1::InspectSocket)?;
    if domain != AddressFamily::UNIX {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::WrongSocketDomain);
    }
    let kind =
        socket_type(endpoint).map_err(KfdTargetDebugTelemetryTransportErrorV1::InspectSocket)?;
    if kind != SocketType::SEQPACKET {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::WrongSocketType);
    }
    if getpeername(endpoint)
        .map_err(KfdTargetDebugTelemetryTransportErrorV1::InspectSocket)?
        .is_none()
    {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::UnconnectedSocket);
    }
    socket_peercred(endpoint).map_err(KfdTargetDebugTelemetryTransportErrorV1::InspectSocket)?;
    Ok(())
}

fn receive_packet(
    endpoint: &OwnedFd,
    flags: RecvFlags,
    target: KfdTargetDebugTelemetryProcessV1,
) -> Result<
    Option<[u8; KFD_TARGET_DEBUG_TELEMETRY_WIRE_LEN_V1]>,
    KfdTargetDebugTelemetryTransportErrorV1,
> {
    let mut bytes = [0_u8; KFD_TARGET_DEBUG_TELEMETRY_WIRE_LEN_V1];
    let mut control_storage =
        [MaybeUninit::uninit(); rustix::cmsg_space!(ScmCredentials(1), ScmRights(4))];
    let mut control = RecvAncillaryBuffer::new(&mut control_storage);
    let mut vectors = [IoSliceMut::new(&mut bytes)];
    let message = loop {
        match recvmsg(endpoint, &mut vectors, &mut control, flags) {
            Ok(message) => break message,
            Err(rustix::io::Errno::INTR) => continue,
            Err(rustix::io::Errno::AGAIN) if flags.contains(RecvFlags::DONTWAIT) => {
                return Ok(None);
            }
            Err(error) => return Err(KfdTargetDebugTelemetryTransportErrorV1::Receive(error)),
        }
    };
    let mut credentials = None;
    let mut forbidden_ancillary = false;
    for item in control.drain() {
        match item {
            RecvAncillaryMessage::ScmCredentials(value) => {
                if credentials.replace(value).is_some() {
                    forbidden_ancillary = true;
                }
            }
            RecvAncillaryMessage::ScmRights(rights) => {
                drop(rights);
                forbidden_ancillary = true;
            }
            _ => forbidden_ancillary = true,
        }
    }
    if message.flags.contains(ReturnFlags::TRUNC) {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::PacketTruncated);
    }
    if message.flags.contains(ReturnFlags::CTRUNC) {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::AncillaryDataTruncated);
    }
    if forbidden_ancillary {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::ForbiddenAncillaryData);
    }
    if message.bytes == 0 {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::UnexpectedEof);
    }
    if message.bytes != bytes.len() {
        return Err(
            KfdTargetDebugTelemetryTransportErrorV1::InvalidPacketLength {
                expected: bytes.len(),
                actual: message.bytes,
            },
        );
    }
    let credentials =
        credentials.ok_or(KfdTargetDebugTelemetryTransportErrorV1::MissingPeerCredentials)?;
    if !target.matches_credentials(
        credentials.pid.as_raw_pid(),
        credentials.uid.as_raw(),
        credentials.gid.as_raw(),
    ) {
        return Err(KfdTargetDebugTelemetryTransportErrorV1::PeerCredentialMismatch);
    }
    target.validate_after_authenticated_packet()?;
    Ok(Some(bytes))
}

fn admit_lifecycle(
    lifecycle: TelemetryLifecycleV1,
    payload: &KfdTargetDebugTelemetryPayloadV1,
) -> Result<(), KfdTargetDebugTelemetryProtocolErrorV1> {
    match (lifecycle, payload) {
        (
            TelemetryLifecycleV1::AwaitingStart,
            KfdTargetDebugTelemetryPayloadV1::SessionStarted { .. },
        )
        | (TelemetryLifecycleV1::Active, KfdTargetDebugTelemetryPayloadV1::Artifact { .. })
        | (TelemetryLifecycleV1::Active, KfdTargetDebugTelemetryPayloadV1::Dispatch { .. })
        | (TelemetryLifecycleV1::Active, KfdTargetDebugTelemetryPayloadV1::Allocation { .. })
        | (TelemetryLifecycleV1::Active, KfdTargetDebugTelemetryPayloadV1::Diagnostic { .. })
        | (TelemetryLifecycleV1::Active, KfdTargetDebugTelemetryPayloadV1::SessionEnded { .. }) => {
            Ok(())
        }
        (TelemetryLifecycleV1::Finished, _) => {
            Err(KfdTargetDebugTelemetryProtocolErrorV1::RecordAfterSessionEnd)
        }
        (TelemetryLifecycleV1::AwaitingStart, _) => {
            Err(KfdTargetDebugTelemetryProtocolErrorV1::MissingSessionStart)
        }
        (TelemetryLifecycleV1::Active, KfdTargetDebugTelemetryPayloadV1::SessionStarted { .. }) => {
            Err(KfdTargetDebugTelemetryProtocolErrorV1::DuplicateSessionStart)
        }
    }
}

fn next_lifecycle(
    current: TelemetryLifecycleV1,
    payload: &KfdTargetDebugTelemetryPayloadV1,
) -> TelemetryLifecycleV1 {
    match payload {
        KfdTargetDebugTelemetryPayloadV1::SessionStarted { .. } => TelemetryLifecycleV1::Active,
        KfdTargetDebugTelemetryPayloadV1::SessionEnded { .. } => TelemetryLifecycleV1::Finished,
        _ => current,
    }
}

fn read_process_start_time(pid: u32) -> Result<u64, KfdTargetDebugTelemetryProcessErrorV1> {
    let bytes =
        read_bounded_proc_file(format!("/proc/{pid}/stat"), MAX_PROC_STAT_BYTES_V1, "stat")?;
    let text = std::str::from_utf8(&bytes)
        .map_err(|_| KfdTargetDebugTelemetryProcessErrorV1::MalformedStat)?;
    let close = text
        .rfind(')')
        .ok_or(KfdTargetDebugTelemetryProcessErrorV1::MalformedStat)?;
    let open = text[..close]
        .find('(')
        .ok_or(KfdTargetDebugTelemetryProcessErrorV1::MalformedStat)?;
    let observed_pid = text[..open]
        .trim()
        .parse::<u32>()
        .map_err(|_| KfdTargetDebugTelemetryProcessErrorV1::MalformedStat)?;
    if observed_pid != pid {
        return Err(KfdTargetDebugTelemetryProcessErrorV1::IdentityChanged);
    }
    text[close + 1..]
        .split_whitespace()
        .nth(19)
        .ok_or(KfdTargetDebugTelemetryProcessErrorV1::MalformedStat)?
        .parse()
        .map_err(|_| KfdTargetDebugTelemetryProcessErrorV1::MalformedStat)
}

fn read_process_credentials(pid: u32) -> Result<(u32, u32), KfdTargetDebugTelemetryProcessErrorV1> {
    let bytes = read_bounded_proc_file(
        format!("/proc/{pid}/status"),
        MAX_PROC_STATUS_BYTES_V1,
        "status",
    )?;
    let text = std::str::from_utf8(&bytes)
        .map_err(|_| KfdTargetDebugTelemetryProcessErrorV1::MalformedStatus)?;
    let uid = unique_effective_credential(text, "Uid:")?;
    let gid = unique_effective_credential(text, "Gid:")?;
    Ok((uid, gid))
}

fn unique_effective_credential(
    text: &str,
    field: &'static str,
) -> Result<u32, KfdTargetDebugTelemetryProcessErrorV1> {
    let mut matches = text.lines().filter(|line| line.starts_with(field));
    let line = matches
        .next()
        .ok_or(KfdTargetDebugTelemetryProcessErrorV1::MalformedStatus)?;
    if matches.next().is_some() {
        return Err(KfdTargetDebugTelemetryProcessErrorV1::MalformedStatus);
    }
    line[field.len()..]
        .split_whitespace()
        .nth(1)
        .ok_or(KfdTargetDebugTelemetryProcessErrorV1::MalformedStatus)?
        .parse()
        .map_err(|_| KfdTargetDebugTelemetryProcessErrorV1::MalformedStatus)
}

fn read_bounded_proc_file(
    path: String,
    limit: u64,
    operation: &'static str,
) -> Result<Vec<u8>, KfdTargetDebugTelemetryProcessErrorV1> {
    let file = File::open(path)
        .map_err(|source| KfdTargetDebugTelemetryProcessErrorV1::ProcIo { operation, source })?;
    let mut bytes = Vec::new();
    file.take(limit + 1)
        .read_to_end(&mut bytes)
        .map_err(|source| KfdTargetDebugTelemetryProcessErrorV1::ProcIo { operation, source })?;
    if bytes.len() as u64 > limit {
        return Err(KfdTargetDebugTelemetryProcessErrorV1::ProcFileTooLarge { operation, limit });
    }
    Ok(bytes)
}

