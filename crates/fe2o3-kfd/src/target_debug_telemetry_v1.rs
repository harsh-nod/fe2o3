/// Best-effort Linux process-instance binding for one telemetry peer.
///
/// The binding combines the PID visible in the receiver's PID namespace, its
/// `/proc` start-time tick, and effective Unix credentials. The receiver checks
/// packet `SCM_CREDENTIALS` and rechecks `/proc` while the peer remains visible.
/// A packet already queued when the peer exits is accepted only after its
/// kernel credentials, connected endpoint, nonce, and sequence all match. This
/// detects ordinary PID reuse while preserving the target's final queued
/// record. It is not a pidfd, a process-control capability, or proof about
/// namespaces not visible through this procfs.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct KfdTargetDebugTelemetryProcessV1 {
    pid: u32,
    start_time_ticks: u64,
    effective_uid: u32,
    effective_gid: u32,
}

impl KfdTargetDebugTelemetryProcessV1 {
    /// Captures one currently live Linux process without granting authority to it.
    pub fn capture(pid: u32) -> Result<Self, KfdTargetDebugTelemetryProcessErrorV1> {
        if pid == 0 || i32::try_from(pid).is_err() {
            return Err(KfdTargetDebugTelemetryProcessErrorV1::InvalidPid);
        }
        let before = read_process_start_time(pid)?;
        let (effective_uid, effective_gid) = read_process_credentials(pid)?;
        let after = read_process_start_time(pid)?;
        if before != after {
            return Err(KfdTargetDebugTelemetryProcessErrorV1::IdentityChanged);
        }
        Ok(Self {
            pid,
            start_time_ticks: before,
            effective_uid,
            effective_gid,
        })
    }

    pub const fn pid(self) -> u32 {
        self.pid
    }

    pub const fn start_time_ticks(self) -> u64 {
        self.start_time_ticks
    }

    pub const fn effective_uid(self) -> u32 {
        self.effective_uid
    }

    pub const fn effective_gid(self) -> u32 {
        self.effective_gid
    }

    /// Opaque V2 correlation identity for this exact process occurrence.
    pub fn correlation_identity_v2(
        self,
    ) -> Result<KfdTargetDebugTelemetryDigestV1, KfdTargetDebugTelemetryDataErrorV1> {
        let mut digest = Sha256::new();
        digest.update(b"fe2o3-kfd-target-process-instance-v2\0");
        digest.update(self.pid.to_le_bytes());
        digest.update(self.start_time_ticks.to_le_bytes());
        digest.update(self.effective_uid.to_le_bytes());
        digest.update(self.effective_gid.to_le_bytes());
        KfdTargetDebugTelemetryDigestV1::from_bytes(digest.finalize().into())
    }

    pub(super) fn validate_current(self) -> Result<(), KfdTargetDebugTelemetryProcessErrorV1> {
        if Self::capture(self.pid)? != self {
            return Err(KfdTargetDebugTelemetryProcessErrorV1::IdentityChanged);
        }
        Ok(())
    }

    pub(super) fn validate_after_authenticated_packet(
        self,
    ) -> Result<(), KfdTargetDebugTelemetryProcessErrorV1> {
        match self.validate_current() {
            Err(KfdTargetDebugTelemetryProcessErrorV1::ProcIo { source, .. })
                if source.kind() == std::io::ErrorKind::NotFound =>
            {
                // SCM_CREDENTIALS describes the sender at send time. A seqpacket may remain
                // queued after that process exits, and the connected inherited endpoint plus
                // session nonce still identify the session. Every other procfs failure remains
                // fail-closed.
                Ok(())
            }
            result => result,
        }
    }

    pub(super) fn matches_credentials(self, pid: i32, uid: u32, gid: u32) -> bool {
        u32::try_from(pid).ok() == Some(self.pid)
            && uid == self.effective_uid
            && gid == self.effective_gid
    }
}

/// Creates a close-on-exec connected channel for provisioning across a target exec.
///
/// The caller retains the debugger descriptor and deliberately exposes only
/// the target descriptor across exec. Clearing close-on-exec and assigning a
/// child ABI descriptor are intentionally owned by the process launcher. The
/// returned descriptors are telemetry-only sockets and contain no KFD handle.
pub fn create_kfd_target_debug_telemetry_channel_v1()
-> Result<(OwnedFd, OwnedFd), KfdTargetDebugTelemetryTransportErrorV1> {
    socketpair(
        AddressFamily::UNIX,
        SocketType::SEQPACKET,
        SocketFlags::CLOEXEC,
        None,
    )
    .map_err(KfdTargetDebugTelemetryTransportErrorV1::CreateChannel)
}

/// Admits the telemetry endpoint deliberately inherited by `fe2o3-debug live-kfd`.
///
/// All three ABI variables must be absent or present together. The inherited
/// descriptor is duplicated atomically with close-on-exec before validation
/// and is never closed by this helper, so hostile environment input cannot make
/// the process close an unrelated descriptor. Only after the duplicate passes
/// endpoint and debugger-credential admission is the inherited original marked
/// close-on-exec. The environment is not mutated; callers may invoke this from
/// a multithreaded process, and stale text alone grants no socket authority.
pub fn admit_inherited_kfd_target_debug_telemetry_v1()
-> Result<Option<KfdCooperativeTargetTelemetryEndpointV1>, KfdInheritedTargetDebugTelemetryErrorV1>
{
    let descriptor = std::env::var_os(KFD_TARGET_DEBUG_TELEMETRY_FD_ENV_V1);
    let nonce = std::env::var_os(KFD_TARGET_DEBUG_TELEMETRY_NONCE_ENV_V1);
    let debugger = std::env::var_os(KFD_TARGET_DEBUG_TELEMETRY_DEBUGGER_PID_ENV_V1);
    if descriptor.is_none() && nonce.is_none() && debugger.is_none() {
        return Ok(None);
    }
    let (descriptor, nonce, debugger) = match (descriptor, nonce, debugger) {
        (Some(descriptor), Some(nonce), Some(debugger)) => (descriptor, nonce, debugger),
        _ => return Err(KfdInheritedTargetDebugTelemetryErrorV1::IncompleteEnvironment),
    };
    let descriptor = descriptor
        .to_str()
        .and_then(decode_canonical_decimal_v1::<i32>)
        .filter(|value| *value >= 3)
        .ok_or(KfdInheritedTargetDebugTelemetryErrorV1::InvalidDescriptor)?;
    let nonce = nonce
        .to_str()
        .and_then(decode_nonce_hex_v1)
        .ok_or(KfdInheritedTargetDebugTelemetryErrorV1::InvalidNonce)
        .and_then(|bytes| {
            KfdTargetDebugSessionNonceV1::from_bytes(bytes)
                .map_err(|_| KfdInheritedTargetDebugTelemetryErrorV1::InvalidNonce)
        })?;
    let debugger = debugger
        .to_str()
        .and_then(decode_canonical_decimal_v1::<u32>)
        .ok_or(KfdInheritedTargetDebugTelemetryErrorV1::InvalidDebuggerProcess)
        .and_then(|pid| {
            KfdTargetDebugTelemetryProcessV1::capture(pid)
                .map_err(KfdInheritedTargetDebugTelemetryErrorV1::DebuggerProcess)
        })?;
    let endpoint = duplicate_raw_descriptor_cloexec_v1(descriptor)
        .map_err(KfdInheritedTargetDebugTelemetryErrorV1::DuplicateDescriptor)?;
    let endpoint = KfdCooperativeTargetTelemetryEndpointV1::admit(endpoint, nonce, debugger)
        .map_err(KfdInheritedTargetDebugTelemetryErrorV1::Admit)?;
    protect_raw_descriptor_v1(descriptor)
        .map_err(KfdInheritedTargetDebugTelemetryErrorV1::ProtectDescriptor)?;
    Ok(Some(endpoint))
}

pub(super) fn decode_nonce_hex_v1(value: &str) -> Option<[u8; 32]> {
    if value.len() != 64
        || !value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || matches!(byte, b'a'..=b'f'))
    {
        return None;
    }
    let mut output = [0_u8; 32];
    for (index, pair) in value.as_bytes().chunks_exact(2).enumerate() {
        let high = decode_lower_hex_digit_v1(pair[0])?;
        let low = decode_lower_hex_digit_v1(pair[1])?;
        output[index] = high << 4 | low;
    }
    Some(output)
}

pub(super) fn decode_canonical_decimal_v1<T: std::str::FromStr>(value: &str) -> Option<T> {
    if !value
        .as_bytes()
        .first()
        .is_some_and(|byte| matches!(byte, b'1'..=b'9'))
        || !value.bytes().all(|byte| byte.is_ascii_digit())
    {
        return None;
    }
    value.parse().ok()
}

pub(super) fn duplicate_raw_descriptor_cloexec_v1(
    descriptor: i32,
) -> Result<OwnedFd, rustix::io::Errno> {
    // SAFETY: fcntl treats the scalar as an index into the calling process's descriptor table.
    // It returns EBADF for an invalid or concurrently closed entry. Only a distinct nonnegative
    // descriptor returned by F_DUPFD_CLOEXEC is converted into Rust ownership.
    let duplicate = unsafe { libc::fcntl(descriptor, libc::F_DUPFD_CLOEXEC, 3) };
    if duplicate < 0 {
        return Err(last_errno_v1());
    }
    // SAFETY: successful F_DUPFD_CLOEXEC returned a fresh descriptor not owned elsewhere.
    Ok(unsafe { OwnedFd::from_raw_fd(duplicate) })
}

pub(super) fn protect_raw_descriptor_v1(descriptor: i32) -> Result<(), rustix::io::Errno> {
    // SAFETY: F_GETFD consumes only the scalar descriptor number and returns EBADF when it is no
    // longer valid. No Rust ownership is constructed for the inherited descriptor.
    let flags = unsafe { libc::fcntl(descriptor, libc::F_GETFD) };
    if flags < 0 {
        return Err(last_errno_v1());
    }
    // SAFETY: F_SETFD changes only the descriptor flags for this scalar table entry.
    if unsafe { libc::fcntl(descriptor, libc::F_SETFD, flags | libc::FD_CLOEXEC) } < 0 {
        return Err(last_errno_v1());
    }
    Ok(())
}

fn last_errno_v1() -> rustix::io::Errno {
    rustix::io::Errno::from_raw_os_error(
        std::io::Error::last_os_error()
            .raw_os_error()
            .unwrap_or(libc::EIO),
    )
}

fn decode_lower_hex_digit_v1(value: u8) -> Option<u8> {
    match value {
        b'0'..=b'9' => Some(value - b'0'),
        b'a'..=b'f' => Some(value - b'a' + 10),
        _ => None,
    }
}

