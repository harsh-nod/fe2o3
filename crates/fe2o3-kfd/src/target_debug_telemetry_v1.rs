//! Cooperative target telemetry for the direct-KFD debugger.
//!
//! This channel carries bounded declarations made by the debug target. Linux
//! credentials attribute each received packet to the process captured by the
//! debugger, but they do not make the declared artifact, dispatch, allocation,
//! or diagnostic content true. In particular, this protocol does not prove
//! that a code object was loaded, a dispatch reached KFD or a GPU, an
//! allocation exists, or a diagnostic describes an observed fault. Consumers
//! must retain the `declared` truth class and correlate these records with
//! independent KFD observations and admitted artifact bytes.
//!
//! The inherited `AF_UNIX` `SOCK_SEQPACKET` endpoint grants no KFD, ptrace,
//! target-memory, register, queue-control, or filesystem authority. Wire
//! records contain only fixed enums, bounded integer metadata, lengths, and
//! opaque 32-byte identities. They never encode paths, native pointers,
//! addresses, or file descriptors. The session nonce prevents accidental
//! cross-session correlation; it is not a secret or an authentication key.

