/// An opaque logical identity carried by cooperative telemetry.
///
/// The bytes are expected to be a domain-separated digest computed by the
/// producer. This type checks only that the value is nonzero; it neither
/// recomputes nor authenticates the digest.
#[derive(Clone, Copy, Eq, Hash, PartialEq)]
pub struct KfdTargetDebugTelemetryDigestV1([u8; 32]);

impl KfdTargetDebugTelemetryDigestV1 {
    pub fn from_bytes(bytes: [u8; 32]) -> Result<Self, KfdTargetDebugTelemetryDataErrorV1> {
        if bytes == [0; 32] {
            return Err(KfdTargetDebugTelemetryDataErrorV1::ZeroDigest);
        }
        Ok(Self(bytes))
    }

    pub const fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }
}

impl fmt::Debug for KfdTargetDebugTelemetryDigestV1 {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("KfdTargetDebugTelemetryDigestV1(")?;
        write_hex(formatter, &self.0)?;
        formatter.write_str(")")
    }
}

