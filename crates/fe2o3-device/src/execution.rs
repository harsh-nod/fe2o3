//! Branded, target-neutral execution capabilities.
//!
//! The source types in this module make kernel, workgroup, subgroup, and
//! synchronization-epoch substitution visible to Rust's type checker. They do
//! not prove convergence, race freedom, target support, or launch validity.
//! Production lowering must establish those dynamic obligations before it may
//! replace any fail-closed terminal in this module.

use core::marker::PhantomData;

