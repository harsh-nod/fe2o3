/// Initial synchronization epoch for one compiler-issued workgroup scope.
#[derive(Debug)]
pub enum InitialEpoch {}

/// Epoch reached after one typed barrier, collective, or async wait.
pub struct NextEpoch<Previous> {
    _previous: PhantomData<Invariant<Previous>>,
}

/// Fresh synchronization epoch issued for one dynamic workgroup phase.
///
/// The lifetime is generated by [`ReusableWorkgroup::with_phase`]. It cannot be
/// named by the caller before the phase begins or retained after it ends.
#[rustc_diagnostic_item = "fe2o3_device_dynamic_phase_epoch_v1"]
pub struct DynamicPhaseEpoch<'phase> {
    _phase: PhantomData<InvariantLifetime<'phase>>,
}

/// Sealed synchronization-epoch identity.
pub trait SynchronizationEpoch: sealed::Epoch {}

/// Sealed proof that an epoch belongs to one reusable dynamic phase.
pub trait ReusableSynchronizationEpoch<'phase>:
    SynchronizationEpoch + sealed::ReusableEpoch<'phase>
{
}

impl sealed::Epoch for InitialEpoch {}
impl SynchronizationEpoch for InitialEpoch {}
impl<Previous: SynchronizationEpoch> sealed::Epoch for NextEpoch<Previous> {}
impl<Previous: SynchronizationEpoch> SynchronizationEpoch for NextEpoch<Previous> {}
impl sealed::Epoch for DynamicPhaseEpoch<'_> {}
impl SynchronizationEpoch for DynamicPhaseEpoch<'_> {}
impl<'phase> sealed::ReusableEpoch<'phase> for DynamicPhaseEpoch<'phase> {}
impl<'phase> ReusableSynchronizationEpoch<'phase> for DynamicPhaseEpoch<'phase> {}
impl<'phase, Previous> sealed::ReusableEpoch<'phase> for NextEpoch<Previous> where
    Previous: ReusableSynchronizationEpoch<'phase>
{
}
impl<'phase, Previous> ReusableSynchronizationEpoch<'phase> for NextEpoch<Previous> where
    Previous: ReusableSynchronizationEpoch<'phase>
{
}

