/// Integer element accepted by scoped atomic terminals.
pub trait AtomicElement: sealed::AtomicElement + Copy {}
/// Ordering accepted by atomic loads.
pub trait AtomicLoadOrdering: MemoryOrdering + sealed::AtomicLoadOrder {}
/// Ordering accepted by atomic stores.
pub trait AtomicStoreOrdering: MemoryOrdering + sealed::AtomicStoreOrder {}
/// Ordering accepted by read-modify-write atomics.
pub trait AtomicRmwOrdering: MemoryOrdering + sealed::AtomicRmwOrder {}
/// Ordering accepted for compare-exchange failure.
pub trait AtomicFailureOrdering: MemoryOrdering + sealed::AtomicFailureOrder {}
/// Scope accepted by atomics issued from a workgroup capability.
pub trait WorkgroupAtomicScope: MemoryScope + sealed::WorkgroupAtomicScope {}

sealed_markers!(AtomicElement => AtomicElement: u32, i32, u64, i64);
sealed_markers!(AtomicLoadOrder => AtomicLoadOrdering: Relaxed, Acquire, SequentiallyConsistent);
sealed_markers!(AtomicStoreOrder => AtomicStoreOrdering: Relaxed, Release, SequentiallyConsistent);
sealed_markers!(AtomicRmwOrder => AtomicRmwOrdering: Relaxed, Acquire, Release, AcquireRelease, SequentiallyConsistent);
sealed_markers!(AtomicFailureOrder => AtomicFailureOrdering: Relaxed, Acquire, SequentiallyConsistent);
sealed_markers!(WorkgroupAtomicScope => WorkgroupAtomicScope: SystemScope, DeviceScope, WorkgroupScope);

/// Type-level compare-exchange success/failure ordering pair.
pub struct AtomicOrderPair<Success, Failure> {
    _success: PhantomData<Invariant<Success>>,
    _failure: PhantomData<Invariant<Failure>>,
}

/// Sealed proof that a compare-exchange ordering pair is valid.
pub trait ValidAtomicOrderPair: sealed::AtomicOrderPair {}

macro_rules! atomic_order_pairs {
    ($($success:ty => [$($failure:ty),+]),+ $(,)?) => {
        $($(
            impl sealed::AtomicOrderPair for AtomicOrderPair<$success, $failure> {}
            impl ValidAtomicOrderPair for AtomicOrderPair<$success, $failure> {}
        )+)+
    };
}

atomic_order_pairs!(
    Relaxed => [Relaxed],
    Acquire => [Relaxed, Acquire],
    Release => [Relaxed],
    AcquireRelease => [Relaxed, Acquire],
    SequentiallyConsistent => [Relaxed, Acquire, SequentiallyConsistent],
);

impl<'kernel, Kernel, Target, Launch> KernelContext<'kernel, Kernel, Target, Launch>
where
    Target: KernelTarget,
    Launch: KernelLaunch,
{
    /// Issues initial-epoch workgroup authority from this exact kernel context.
    #[doc(hidden)]
    #[inline(never)]
    #[rustc_diagnostic_item = "fe2o3_device_workgroup_capability_current_v1"]
    pub fn __compiler_workgroup_capability_current<'workgroup>(
        &'workgroup mut self,
    ) -> WorkgroupCapability<
        'workgroup,
        KernelCapabilityBrand<'kernel, Kernel, Target, Launch>,
        InitialEpoch,
    > {
        unreachable!("workgroup capability issuance requires authenticated lowering")
    }

    /// Opens one generative capability scope for the current workgroup.
    ///
    /// The higher-ranked lifetime prevents workgroup, subgroup, LDS, epoch,
    /// atomic, and async-copy capabilities from escaping into another dynamic
    /// workgroup invocation.
    pub fn with_workgroup<Result>(
        &mut self,
        operation: impl for<'workgroup> FnOnce(
            WorkgroupCapability<
                'workgroup,
                KernelCapabilityBrand<'kernel, Kernel, Target, Launch>,
                InitialEpoch,
            >,
        ) -> Result,
    ) -> Result {
        let workgroup = self.__compiler_workgroup_capability_current();
        operation(workgroup)
    }
}

