struct BorrowedAssertionComponentsV1<'s> {
    types: &'s [SemanticTypeDeclV1],
    function: &'s SemanticFunctionDeclV1,
    graph: &'s ProjectedLoopCfgV1,
    counts: &'s [u8],
    blocks: &'s [Vec<usize>],
    escaped: &'s [bool],
    assignments: &'s [Option<ScalarAssignmentSiteV1>],
}

/// No source authority is created by this common private evaluator core.
fn analyze_borrowed_assertion_components_v1(
    components: BorrowedAssertionComponentsV1<'_>,
    resources: &mut PreparationResourcesV1<'_, '_>,
) -> Result<(Vec<bool>, usize), ProductionRankedProjectionErrorV1> {
    let mut resources = AssertionResourcesV1::strict(resources)?;
    // Pay this entry's complete constructor/locals/output/error transfer before
    // moving the handle into the actual evaluator. C's envelope is additional.
    resources.reserve_frame::<(Vec<bool>, usize)>(
        std::mem::size_of::<BorrowedAssertionComponentsV1<'static>>()
            .checked_add(assertion_evaluator_local_frame_v1()?)
            .ok_or_else(assertion_resource_overflow_v1)?,
    )?;
    reserve_assertion_evaluator_frames_v1(&mut resources)?;
    let mut proof = SemanticAssertProofsV1::new_borrowed_assertion_tables_v1(
        components.types,
        components.function,
        components.graph,
        components.counts,
        components.blocks,
        components.escaped,
        components.assignments,
        resources,
    )?;
    let decisions = proof.analyze_existing_assertions_v1()?;
    proof.resources.extra_work(64)?;
    if proof.resources.is_denied() || decisions.len() != components.function.blocks().len() {
        return Err(assertion_resource_accounting_v1());
    }
    let logical_work = proof.work;
    // Evaluator/caches and ORIGINAL exclusive adapter borrow end before return.
    // The enclosing owner keeps ALL accepted credits until the mask is dropped.
    drop(proof);
    Ok((decisions, logical_work))
}

pub(super) fn analyze_prepared_root_assertions_with_resources_v1<'s>(
    view: &'s NominalRootCfgSourceV1<'_>,
    resources: &mut PreparationResourcesV1<'_, '_>,
) -> Result<PreparedAssertionDecisionsV1<'s>, ProductionRankedProjectionErrorV1> {
    // The exact entry/transfer is paid on ORIGINAL before source/table assembly.
    // The short handle must end before the common core exclusively borrows it.
    {
        let mut entry = AssertionResourcesV1::strict(resources)?;
        entry.reserve_frame::<PreparedAssertionDecisionsV1<'s>>(std::mem::size_of::<
            BorrowedAssertionComponentsV1<'s>,
        >())?;
        entry.extra_work(64)?;
    }
    let function: &'s SemanticFunctionDeclV1 = view.function();
    let graph: &'s ProjectedLoopCfgV1 = view.graph();
    let types: &'s [SemanticTypeDeclV1] = view.types();
    let rich = view.source_tables().rich();
    if !std::ptr::eq(function, rich.function()) {
        return Err(ProductionRankedProjectionErrorV1::Unsupported(
            "prepared assertion function differs from exact rich source",
        ));
    }
    let (decisions, logical_work) = analyze_borrowed_assertion_components_v1(
        BorrowedAssertionComponentsV1 {
            types,
            function,
            graph,
            counts: rich.scalar_counts(),
            blocks: rich.scalar_blocks(),
            escaped: rich.address_escaped(),
            assignments: rich.scalar_assignments(),
        },
        resources,
    )?;
    Ok(PreparedAssertionDecisionsV1 {
        function,
        graph,
        types,
        decisions,
        logical_work,
    })
}

