pub(super) enum AssertionGraphV1<'a> {
    Owned(ProjectedLoopCfgV1),
    Borrowed(&'a ProjectedLoopCfgV1),
}
impl Deref for AssertionGraphV1<'_> {
    type Target = ProjectedLoopCfgV1;
    fn deref(&self) -> &Self::Target {
        match self {
            Self::Owned(value) => value,
            Self::Borrowed(value) => value,
        }
    }
}
pub(super) enum AssertionTableV1<'a, T> {
    Owned(Vec<T>),
    Borrowed(&'a [T]),
}
impl<T> Deref for AssertionTableV1<'_, T> {
    type Target = [T];
    fn deref(&self) -> &Self::Target {
        match self {
            Self::Owned(value) => value,
            Self::Borrowed(value) => value,
        }
    }
}
impl<T: Clone> Clone for AssertionTableV1<'_, T> {
    fn clone(&self) -> Self {
        // Existing out-of-core callers hold the Owned legacy arm and keep the
        // exact old Vec::clone. The strict evaluator never clones these tables.
        match self {
            Self::Owned(value) => Self::Owned(value.clone()),
            Self::Borrowed(value) => Self::Borrowed(value),
        }
    }
}

