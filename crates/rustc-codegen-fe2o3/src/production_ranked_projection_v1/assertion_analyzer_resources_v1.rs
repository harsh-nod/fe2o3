/// Closed synthetic probes exercise real non-top-level evaluator paths. These
/// variants exist only in test builds; there is no external callback/reentry.
#[cfg(test)]
pub(super) enum AssertionFixedProbeV1<'a> {
    Quotient {
        numerator: &'a SemanticOperandV1,
        divisor: &'a SemanticOperandV1,
        use_site: ScalarAssignmentSiteV1,
    },
    FlatPath {
        operand: &'a SemanticOperandV1,
        operand_use: ScalarAssignmentSiteV1,
        sum_site: ScalarAssignmentSiteV1,
        scalar_type: SemanticTypeIdV1,
        offsets: &'a [(SemanticOperandV1, ScalarAssignmentSiteV1)],
        remaining: usize,
    },
    Nested {
        checked: &'a SemanticCheckedBinaryRvalueV1,
        sum_site: ScalarAssignmentSiteV1,
    },
    PanicAfterRealMask,
}
#[cfg(test)]
pub(super) enum AssertionFixedProbeResultV1 {
    Quotient(Option<AuthenticatedQuotientStrictBoundV1>),
    Flat(bool),
}

/// Test owner must retain every accepted credit until this result (or unwind
/// payload) and all evaluator locals are dropped. No credit transfer/refund here.
#[cfg(test)]
pub(super) fn analyze_assertion_fixed_probe_for_test_v1(
    types: &[SemanticTypeDeclV1],
    function: &SemanticFunctionDeclV1,
    graph: &ProjectedLoopCfgV1,
    inventory: &AssertionDefinitionInventoryV1,
    probe: AssertionFixedProbeV1<'_>,
    resources: &mut PreparationResourcesV1<'_, '_>,
) -> Result<(AssertionFixedProbeResultV1, usize), ProductionRankedProjectionErrorV1> {
    let mut resources = AssertionResourcesV1::strict(resources)?;
    resources.reserve_frame::<(AssertionFixedProbeResultV1, usize)>(
        std::mem::size_of::<AssertionFixedProbeV1<'static>>()
            .checked_add(assertion_evaluator_local_frame_v1()?)
            .ok_or_else(assertion_resource_overflow_v1)?,
    )?;
    reserve_assertion_evaluator_frames_v1(&mut resources)?;
    let mut proof = SemanticAssertProofsV1::new_borrowed_assertion_tables_v1(
        types,
        function,
        graph,
        &inventory.counts,
        &inventory.blocks,
        &inventory.address_escaped,
        &inventory.assignments,
        resources,
    )?;
    let result = match probe {
        AssertionFixedProbeV1::Quotient {
            numerator,
            divisor,
            use_site,
        } => {
            proof
                .resources
                .reserve_frame::<Option<AuthenticatedQuotientStrictBoundV1>>(
                    assertion_evaluator_local_frame_v1()?,
                )?;
            AssertionFixedProbeResultV1::Quotient(
                proof.quotient_strict_product_upper_bound_v1(numerator, divisor, use_site)?,
            )
        }
        AssertionFixedProbeV1::FlatPath {
            operand,
            operand_use,
            sum_site,
            scalar_type,
            offsets,
            remaining,
        } => {
            let capacity = offsets
                .len()
                .checked_add(remaining)
                .ok_or_else(assertion_resource_overflow_v1)?;
            let mut copied_offsets = Vec::new();
            proof.resources.reserve_vec(
                &mut copied_offsets,
                capacity,
                LegacyReserve::Exact,
                "test flat-index offset storage cannot be reserved",
            )?;
            proof.resources.extra_work(offsets.len())?;
            for (operand, site) in offsets {
                let copied = proof.resources.clone_operand(operand)?;
                let value = (copied, *site);
                SemanticAssertProofsV1::push_assertion_reserved_vec_v1(
                    &mut proof.resources,
                    &mut copied_offsets,
                    value,
                )?;
            }
            proof
                .resources
                .reserve_frame::<bool>(assertion_evaluator_local_frame_v1()?)?;
            AssertionFixedProbeResultV1::Flat(
                proof.proves_strictly_bounded_unsigned_flat_index_path_v1(
                    operand,
                    operand_use,
                    sum_site,
                    scalar_type,
                    &mut copied_offsets,
                    remaining,
                )?,
            )
        }
        AssertionFixedProbeV1::Nested { checked, sum_site } => AssertionFixedProbeResultV1::Flat(
            proof.proves_strictly_bounded_unsigned_nested_flat_index_v1(checked, sum_site)?,
        ),
        AssertionFixedProbeV1::PanicAfterRealMask => {
            let _actual_mask = proof.analyze_existing_assertions_v1()?;
            // Static test panic only: no arbitrary callback into a live analyzer.
            proof.resources.reserve_frame::<&'static str>(0)?;
            proof.resources.extra_work(64)?;
            panic!("synthetic assertion evaluator unwind after real mask");
        }
    };
    proof.resources.extra_work(64)?;
    if proof.resources.is_denied() {
        return Err(assertion_resource_accounting_v1());
    }
    let logical_work = proof.work;
    drop(proof);
    Ok((result, logical_work))
}
